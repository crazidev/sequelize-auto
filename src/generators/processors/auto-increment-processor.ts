import { Field } from '../../types';
import { AttributeProcessor } from './attribute-processor';
import { Decorator, FieldAttribute, ProcessorContext } from '../types/model-structure';

export class AutoIncrementProcessor implements AttributeProcessor {
  canProcess(attrName: string, version: 'v6' | 'v7'): boolean {
    return attrName === 'autoIncrement';
  }

  process(
    fieldObj: Field,
    attrName: string,
    attrValue: any,
    context: ProcessorContext
  ): FieldAttribute | null {
    if (attrValue === true && context.isSerialKey) {
      const result: FieldAttribute = {
        name: 'autoIncrement',
        value: true,
        format: 'v6',
      };

      // Postgres GENERATED BY DEFAULT AS IDENTITY
      if (
        context.dialect.name === 'postgres' &&
        fieldObj.foreignKey &&
        fieldObj.foreignKey.isPrimaryKey === true &&
        (fieldObj.foreignKey.generation === 'ALWAYS' || fieldObj.foreignKey.generation === 'BY DEFAULT')
      ) {
        // Note: autoIncrementIdentity is handled separately if needed
      }

      return result;
    }
    return null;
  }

  getDecorators(
    fieldObj: Field,
    attrName: string,
    attrValue: any,
    context: ProcessorContext
  ): Decorator[] | undefined {
    if (attrValue === true && context.isSerialKey) {
      return [
        {
          name: 'AutoIncrement',
        },
      ];
    }
    return undefined;
  }
}
